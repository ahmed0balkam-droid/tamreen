// Build: core.js -> createCore factory (for tests) and the single-file Supabase Edge Function.
const fs = require('fs');
const path = require('path');
const D = __dirname;
const core = fs.readFileSync(path.join(D, 'src/core.js'), 'utf8');
const db = fs.readFileSync(path.join(D, 'src/db.js'), 'utf8').replace(/\nif \(typeof module[^\n]*\n?/, '\n');

// public API = top-level functions without a trailing underscore
const api = [...core.matchAll(/^function ([A-Za-z]+[a-zA-Z0-9]*[a-zA-Z0-9])\(/gm)].map((m) => m[1]).filter((n) => !n.endsWith('_'));

const factory = `function createCore(TX) {\n${core}\n  return { api: { ${api.map((n) => n + ': ' + n).join(', ')} }, setting_: setting_, fair100_: fair100_ };\n}\n`;
fs.mkdirSync(path.join(D, 'dist'), { recursive: true }); fs.mkdirSync(path.join(D, 'supabase/functions/api'), { recursive: true });
fs.writeFileSync(path.join(D, 'dist/core_factory.js'), factory + 'module.exports = { createCore };\n');

const edge = `// ⚽ تمرين السبت — Supabase Edge Function "api" (generated by build.js — edit src/ instead)
// deno-lint-ignore-file
import postgres from "npm:postgres@3.4.5";

const sql = postgres(Deno.env.get("SUPABASE_DB_URL")!, { max: Number(Deno.env.get("DB_POOL") || 3), prepare: false, idle_timeout: 20 });
const tx = (fn: (q: (t: string, p: unknown[]) => Promise<any[]>) => Promise<any>) =>
  sql.begin((t: any) => fn((text: string, params: unknown[]) => t.unsafe(text, params as any[])));

const CORS = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Methods": "POST, OPTIONS",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type",
};
const json = (o: unknown, status = 200) => new Response(JSON.stringify(o), { status, headers: { ...CORS, "Content-Type": "application/json; charset=utf-8" } });

${factory}
${db}

const API = new Set(${JSON.stringify(api.filter((n) => n !== 'setup'))});

Deno.serve(async (req: Request) => {
  if (req.method === "OPTIONS") return new Response("ok", { headers: CORS });
  if (req.method !== "POST") return json({ ok: true, app: "tamreen" });
  let body: any;
  try { body = await req.json(); } catch { return json({ error: "طلب غير صالح." }, 400); }
  const fn = String(body?.fn || "");
  // setup / importSheets only work once, on an empty database
  if (!API.has(fn) && fn !== "setup" && fn !== "importSheets") return json({ error: "طلب غير معروف." }, 400);
  try {
    const data = fn === "importSheets" ? await importSheets(tx, body?.arg?.csv || {}) : await runCall(tx, createCore, fn, body?.arg || {});
    return json({ data });
  } catch (e) {
    const msg = e instanceof Error ? e.message : String(e);
    const user = /[\\u0600-\\u06FF]/.test(msg);           // our own Arabic messages go back to the page as-is
    if (!user) console.error(fn, e);
    return json({ error: user ? msg : "صار خطأ في الخادم، حاول مرة ثانية." }, user ? 200 : 500);
  }
});
`;
fs.writeFileSync(path.join(D, 'supabase/functions/api/index.ts'), edge);
console.log('api:', api.length, 'functions; edge', edge.length, 'chars');
